import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { execSync } from 'node:child_process';
import { buildIdentityPlugin } from './scripts/build-id-plugin.mjs';

// The revision must resolve identically in CI and in a plain local clone, so
// production artifacts are reproducible from source with the committed lockfile.
const buildRevision = process.env.GITHUB_SHA?.slice(0, 8)
	?? (() => {
		try {
			return execSync('git rev-parse --short=8 HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
		} catch {
			return 'local';
		}
	})();

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'node:crypto',
		'node:child_process',
		'node:fs',
		'node:fs/promises',
		'node:os',
		'node:path',
		'node:timers/promises',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	plugins: [buildIdentityPlugin(buildRevision, { deterministic: prod })],
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
